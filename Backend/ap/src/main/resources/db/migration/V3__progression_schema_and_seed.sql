-- V3 — the progression engine schema (phase plan P1) and its seed config.
--
-- Tables:
--   quest_templates  quest definitions, filtered by level at generation time
--   user_quests      one user's quests for one day (template values snapshotted)
--   xp_ledger        append-only XP awards; unique idempotency key = exactly-once
--   day_summaries    per-day XP + quests completed; streaks are derived from it
--   level_curve      config: XP needed to go from L to L+1 (mechanics §6.1)
--   ranks            config: the E->S ladder and its XP multipliers (§6.2)
--   user_stats       cached, derived progression state (always recomputable)
--
-- Note: the rank column is rank_code because RANK is a reserved word in MySQL 8.

CREATE TABLE quest_templates (
    id          BIGINT       NOT NULL AUTO_INCREMENT,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255) NULL,
    type        VARCHAR(32)  NOT NULL,
    target      BIGINT       NOT NULL,
    unit        VARCHAR(32)  NULL,
    stat_code   VARCHAR(16)  NULL,
    stat_amount BIGINT       NULL,
    xp_reward   BIGINT       NOT NULL,
    min_level   INT          NOT NULL DEFAULT 1,
    PRIMARY KEY (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE user_quests (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    user_id      BIGINT       NOT NULL,
    quest_date   DATE         NOT NULL,
    template_id  BIGINT       NOT NULL,
    name         VARCHAR(255) NOT NULL,
    description  VARCHAR(255) NULL,
    type         VARCHAR(32)  NOT NULL,
    target       BIGINT       NOT NULL,
    unit         VARCHAR(32)  NULL,
    stat_code    VARCHAR(16)  NULL,
    stat_amount  BIGINT       NULL,
    xp_reward    BIGINT       NOT NULL,
    logged       BIGINT       NOT NULL DEFAULT 0,
    completed    BOOLEAN      NOT NULL DEFAULT FALSE,
    awarded_xp   BIGINT       NULL,
    completed_at TIMESTAMP    NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_user_quests_day_template UNIQUE (user_id, quest_date, template_id),
    CONSTRAINT fk_user_quests_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_quests_template FOREIGN KEY (template_id) REFERENCES quest_templates (id),
    INDEX idx_user_quests_user_date (user_id, quest_date)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE xp_ledger (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    user_id         BIGINT       NOT NULL,
    amount          BIGINT       NOT NULL,
    source          VARCHAR(32)  NOT NULL,
    quest_id        BIGINT       NULL,
    quest_date      DATE         NOT NULL,
    idempotency_key VARCHAR(191) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_xp_ledger_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_xp_ledger_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_xp_ledger_quest FOREIGN KEY (quest_id) REFERENCES user_quests (id),
    INDEX idx_xp_ledger_user_date (user_id, quest_date)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE day_summaries (
    id               BIGINT NOT NULL AUTO_INCREMENT,
    user_id          BIGINT NOT NULL,
    quest_date       DATE   NOT NULL,
    xp_earned        BIGINT NOT NULL DEFAULT 0,
    quests_completed BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_day_summaries_user_date UNIQUE (user_id, quest_date),
    CONSTRAINT fk_day_summaries_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE level_curve (
    level      INT    NOT NULL,
    xp_to_next BIGINT NOT NULL,
    PRIMARY KEY (level)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE ranks (
    rank_code     VARCHAR(8)  NOT NULL,
    min_level     INT         NOT NULL,
    max_level     INT         NULL,
    color         VARCHAR(32) NULL,
    xp_multiplier DOUBLE      NOT NULL DEFAULT 1.0,
    PRIMARY KEY (rank_code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE user_stats (
    user_id        BIGINT     NOT NULL,
    total_xp       BIGINT     NOT NULL DEFAULT 0,
    level          INT        NOT NULL DEFAULT 1,
    rank_code      VARCHAR(8) NULL,
    current_streak BIGINT     NOT NULL DEFAULT 0,
    best_streak    BIGINT     NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id),
    CONSTRAINT fk_user_stats_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

